// Page dates from git: `modified` is the last commit touching a page's files
// (or now, if they have uncommitted edits); `published` is the commit that
// first added the page's main file. Used by next.config.ts at build time.
//
//   npm run lastmod   writes content/lastmod.json for builds without git history.
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const read = (file) => JSON.parse(readFileSync(new URL(`../${file}`, import.meta.url), "utf8"));

function git(args) {
  try {
    return execFileSync("git", args, { cwd: root, encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] }).trim();
  } catch {
    return "";
  }
}

const iso = (d) => new Date(d).toISOString();

/** Dates from git, or null when git history is missing or shallow. */
export function datesFromGit() {
  if (git(["rev-parse", "--is-shallow-repository"]) !== "false") return null;
  const now = iso(Date.now());
  const routes = read("content/sitemap-sources.json").routes;
  return Object.fromEntries(
    Object.entries(routes).map(([route, files]) => {
      const dirty = git(["status", "--porcelain", "--", ...files]) !== "";
      const modified = dirty ? now : git(["log", "-1", "--format=%cI", "--", ...files]);
      const added = git(["log", "--diff-filter=A", "--format=%cI", "--", files[0]]).split("\n").filter(Boolean).pop();
      return [route, { modified: modified ? iso(modified) : now, published: added ? iso(added) : modified ? iso(modified) : now }];
    }),
  );
}

/** Live git dates when available, otherwise the committed content/lastmod.json. */
export function pageDates() {
  const live = datesFromGit();
  if (live) return live;
  return existsSync(new URL("../content/lastmod.json", import.meta.url)) ? read("content/lastmod.json").routes : {};
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const dates = datesFromGit();
  if (!dates) {
    console.error("Full git history is needed. Run this in a normal clone, not a shallow one.");
    process.exit(1);
  }
  writeFileSync(
    new URL("../content/lastmod.json", import.meta.url),
    JSON.stringify({ _note: "Generated by `npm run lastmod`. Do not edit by hand.", routes: dates }, null, 2) + "\n",
  );
  console.log(`content/lastmod.json: ${Object.keys(dates).length} routes`);
}
